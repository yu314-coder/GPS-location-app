    func fetchCumulativeQuantitySum(
        for workout: HKWorkout,
        identifier: HKQuantityTypeIdentifier,
        completion: @escaping (Double?, Error?) -> Void
    ) {
        guard let quantityType = HKQuantityType.quantityType(forIdentifier: identifier) else {
            completion(nil, NSError(domain: "HealthKit", code: -1, userInfo: [NSLocalizedDescriptionKey: "Quantity type unavailable: \(identifier.rawValue)"]))
            return
        }

        let predicate = HKQuery.predicateForObjects(from: workout)
        let query = HKStatisticsQuery(
            quantityType: quantityType,
            quantitySamplePredicate: predicate,
            options: .cumulativeSum
        ) { _, result, error in
            if let error = error {
                completion(nil, error)
                return
            }
            let unit = self.unit(for: identifier)
            completion(result?.sumQuantity()?.doubleValue(for: unit), nil)
        }

        healthStore.execute(query)
    }

    private func unit(for identifier: HKQuantityTypeIdentifier) -> HKUnit {
        switch identifier {
        case .stepCount:
            return .count()
        case .distanceWalkingRunning, .distanceCycling:
            return .meter()
        case .activeEnergyBurned, .basalEnergyBurned:
            return .kilocalorie()
        default:
            return .count()
        }
    }

    func fetchRouteWithRetry(
        for workout: HKWorkout,
        maxRetries: Int = 5,
        retryDelay: TimeInterval = 1.0,
        completion: @escaping ([FlightLocation]?, Error?) -> Void
    ) {
        fetchRoute(for: workout) { [weak self] routeLocations, error in
            if let routeLocations, !routeLocations.isEmpty {
                completion(routeLocations, nil)
                return
            }

            guard maxRetries > 0, let self = self else {
                completion(nil, error ?? NSError(domain: "HealthKit", code: -1, userInfo: [NSLocalizedDescriptionKey: "Route unavailable after retries"]))
                return
            }

            DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + retryDelay) {
                self.fetchRouteWithRetry(
                    for: workout,
                    maxRetries: maxRetries - 1,
                    retryDelay: retryDelay,
                    completion: completion
                )
            }
        }
    }

