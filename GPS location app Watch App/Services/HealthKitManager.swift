    func deleteWorkout(uuid: UUID, completion: @escaping (Bool, Error?) -> Void) {
        let workoutType = HKObjectType.workoutType()
        let predicate = HKQuery.predicateForObject(with: uuid)

        let query = HKSampleQuery(
            sampleType: workoutType,
